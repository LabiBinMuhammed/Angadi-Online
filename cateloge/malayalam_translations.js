function getMalayalamName(productName) {
  if (commonTerms[productName]) {
    return commonTerms[productName];
  }

  for (const [engBrand, mlBrand] of Object.entries(brandPrefixes)) {
    if (productName.startsWith(engBrand + ' ')) {
      const remainder = productName.slice(engBrand.length + 1).trim();
      if (commonTerms[remainder]) {
        return `${mlBrand} ${commonTerms[remainder]}`;
      }
      return `${mlBrand} ${remainder}`;
    }
  }

  // Elite brand cakes without prefix
  if (commonTerms[productName]) {
    return commonTerms[productName];
  }

  return productName;
}

module.exports = { getMalayalamName, brandPrefixes, commonTerms };
